public class MonthOuthOfRangeException extends RuntimeException {
    public MonthOuthOfRangeException(String message) {
        super(message);

    }

    public MonthOuthOfRangeException(String message, Throwable cause) {
        super(message, cause);
    }

    public MonthOuthOfRangeException(String message, Throwable cause, boolean enableSuppression, boolean writableStackTrace) {
        super(message, cause, enableSuppression, writableStackTrace);
    }

    public MonthOuthOfRangeException() {
    }

    public MonthOuthOfRangeException(Throwable cause) {
        super(cause);
    }
}
